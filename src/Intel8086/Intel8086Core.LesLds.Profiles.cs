    private static int GetLesLdsProfileIndex(byte opcode, int mod, int rm, int queueCount, bool prefixed, bool oddAddress)
    {
        int opcodeOffset = opcode == 0xC5 ? 192 : 0;
        int index = ((((mod * 8 + rm) * 2 + (queueCount >= 6 ? 1 : 0)) * 2 + (prefixed ? 1 : 0)) * 2) + (oddAddress ? 1 : 0);
        return opcodeOffset + index;
    }

