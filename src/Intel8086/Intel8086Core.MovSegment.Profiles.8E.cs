        ((((mod * 8 + rm) * 2 + (queueCount >= 6 ? 1 : 0)) * 2 + (prefixed ? 1 : 0)) * 2) + (oddAddress ? 1 : 0);

    private static Intel8086SegmentMoveProfile GetMovSegmentProfile(byte opcode, int mod, int rm, int queueCount, bool prefixed, bool oddAddress)
    {
        int index = GetMovSegmentProfileIndex(mod, rm, queueCount, prefixed, oddAddress);
        return opcode == 0x8C
            ? new Intel8086SegmentMoveProfile(MovSegment8CBus[index], MovSegment8CCycles[index], MovSegment8CFetch1[index], MovSegment8CFetch2[index], MovSegment8CFetch3[index], MovSegment8CPrefetch[index])
